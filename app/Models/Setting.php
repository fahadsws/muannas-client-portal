<?php

namespace App\Models;

use Illuminate\Database\Eloquent\Model;

class Setting extends Model
{
    public $timestamps = false;
    public $incrementing = false;
    protected $primaryKey = 'key';
    protected $keyType = 'string';
    protected $guarded = [];
    protected $casts = ['value' => 'array'];

    public static function defaults(): array
    {
        return [
            'brand' => config('board.brand'), 'tagline' => config('board.tagline'),
            'default_max_workspaces' => 10, 'default_max_members' => 5,
            'report_header' => '', 'report_footer' => 'Generated by {brand}', 'report_paper' => 'a4',
        ];
    }

    public static function all_(): array
    {
        $saved = static::query()->pluck('value', 'key')->map(fn ($v) => is_array($v) ? ($v[0] ?? null) : $v)->all();

        return array_merge(self::defaults(), $saved);
    }

    public static function put(array $values): void
    {
        foreach ($values as $k => $v) {
            static::updateOrCreate(['key' => $k], ['value' => [$v]]);
        }
    }
}
